using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Aquila.UserId;

/// <summary>
/// Окно, показывающее UUID игрока с кнопкой копирования.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class UserIdWindow : FancyWindow
{
    [Dependency] private readonly IClipboardManager _clipboard = default!;

    public UserIdWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CopyButton.OnPressed += _ => _clipboard.SetText(UserIdEdit.Text);
    }

    public void SetUserId(string userId)
    {
        UserIdEdit.Text = userId;
    }
}
