using Content.Client._Aquila.PDA;
using Content.Client.UserInterface.Controls;
using Content.Shared._Aquila.Economy;
using Content.Shared._Aquila.Economy.DataDefinitions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Aquila.Economy;

[GenerateTypedNameReferences]
public sealed partial class BankAdminWindow : FancyWindow
{
    public event Action<int>? OnSelect;
    public event Action? OnRefresh;
    public event Action<int, int, string>? OnBonus;
    public event Action<int, int, string>? OnFine;
    public event Action<int, int, string>? OnSetBalance;
    public event Action<int, int, int, string>? OnRevert;
    public event Action<int, bool>? OnRequestReply;
    public event Action<int>? OnRevokeFine;

    private BankAdminEuiState? _state;

    public BankAdminWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, Loc.GetString("bank-admin-tab-account"));
        Tabs.SetTabTitle(1, Loc.GetString("bank-admin-tab-requests"));
        Tabs.SetTabTitle(2, Loc.GetString("bank-admin-tab-fines"));

        SearchInput.OnTextChanged += _ => PopulateAccounts();
        CommentInput.OnTextChanged += _ => UpdateButtons();
        AmountInput.OnTextChanged += _ => UpdateButtons();
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        BonusButton.OnPressed += _ => SendAmount(OnBonus);
        FineButton.OnPressed += _ => SendAmount(OnFine);
        SetBalanceButton.OnPressed += _ => SendAmount(OnSetBalance);
    }

    /// <summary>
    /// Обновляет список счетов, выбранный счёт с историей, запросы и штрафы.
    /// </summary>
    public void UpdateState(BankAdminEuiState state)
    {
        _state = state;
        PopulateAccounts();
        PopulateAccount();
        PopulateRecords(RequestsList, NoRequestsLabel, state.Requests, true);
        PopulateRecords(FinesList, NoFinesLabel, state.Fines, false);
        Tabs.SetTabTitle(1, Loc.GetString("bank-admin-tab-requests-count", ("count", state.Requests.Count)));
        UpdateButtons();
    }

    private void PopulateAccounts()
    {
        AccountsList.RemoveAllChildren();
        if (_state == null)
            return;

        var search = SearchInput.Text.Trim();
        foreach (var account in _state.Accounts)
        {
            var text = Loc.GetString("bank-admin-account-row",
                ("name", account.OwnerName),
                ("job", account.JobTitle ?? Loc.GetString("bank-admin-no-job")),
                ("number", account.Number.ToString()),
                ("balance", account.Balance));

            if (search.Length > 0
                && !text.Contains(search, StringComparison.CurrentCultureIgnoreCase))
                continue;

            var number = account.Number;
            var button = new Button
            {
                Text = text,
                ToolTip = text,
                ToggleMode = true,
                Pressed = _state.Selected == number,
                ClipText = true,
                HorizontalExpand = true,
            };
            button.OnPressed += _ => OnSelect?.Invoke(number);
            AccountsList.AddChild(button);
        }
    }

    private void PopulateAccount()
    {
        HistoryList.RemoveAllChildren();
        var account = _state?.Accounts.Find(a => a.Number == _state.Selected);
        NoAccountLabel.Visible = account == null;
        AccountContainer.Visible = account != null;
        if (account == null || _state == null)
            return;

        AccountTitle.Text = Loc.GetString("bank-admin-account-title",
            ("name", account.OwnerName),
            ("number", account.Number.ToString()));
        AccountBalance.Text = Loc.GetString("bank-ui-balance", ("balance", account.Balance));
        AccountBalance.FontColorOverride = account.Balance < 0 ? PdaStyle.Red : null;

        var history = _state.History;
        if (history.Count == 0)
        {
            HistoryList.AddChild(new Label { Text = Loc.GetString("bank-ui-history-empty"), StyleClasses = { "LabelSubText" } });
            return;
        }

        for (var i = history.Count - 1; i >= 0; i--)
        {
            HistoryList.AddChild(CreateTransactionRow(account.Number, i, history[i]));
        }
    }

    private BoxContainer CreateTransactionRow(int number, int index, BankTransaction transaction)
    {
        var reason = Loc.GetString(transaction.Reason, ("party", transaction.Party ?? string.Empty));
        if (transaction.Comment != null)
            reason = Loc.GetString("bank-transaction-with-comment", ("reason", reason), ("comment", transaction.Comment));

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
        row.AddChild(new Label
        {
            Text = transaction.Time.ToString(@"hh\:mm\:ss"),
            StyleClasses = { "LabelSubText" },
            MinWidth = 70,
        });
        row.AddChild(new Label
        {
            Text = Loc.GetString(transaction.Amount > 0 ? "bank-ui-income" : "bank-ui-expense", ("amount", Math.Abs(transaction.Amount))),
            FontColorOverride = transaction.Amount > 0 ? PdaStyle.Accent : PdaStyle.Red,
            MinWidth = 70,
        });
        row.AddChild(new Label
        {
            Text = reason,
            ToolTip = reason,
            HorizontalExpand = true,
            ClipText = true,
        });

        var revert = new Button
        {
            Text = Loc.GetString("bank-admin-revert"),
            StyleClasses = { "OpenLeft" },
        };
        revert.OnPressed += _ => OnRevert?.Invoke(number, index, transaction.Amount, CommentInput.Text);
        row.AddChild(revert);
        return row;
    }

    private void PopulateRecords(BoxContainer list, Label empty, List<BankManageRecordUiData> records, bool requests)
    {
        list.RemoveAllChildren();
        empty.Visible = records.Count == 0;

        foreach (var record in records)
        {
            var title = Loc.GetString(record.Fine ? "bank-ui-manage-record-fine" : "bank-ui-manage-record-bonus",
                ("amount", record.Amount),
                ("target", record.TargetName));
            var details = Loc.GetString("bank-ui-manage-record-details",
                ("issuer", record.IssuerName),
                ("budget", record.BudgetName),
                ("comment", record.Comment));

            var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
            text.AddChild(new Label
            {
                Text = title,
                FontColorOverride = record.Fine ? PdaStyle.Red : PdaStyle.Accent,
                ClipText = true,
            });
            text.AddChild(new Label
            {
                Text = details,
                ToolTip = details,
                StyleClasses = { "LabelSubText" },
                ClipText = true,
            });

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 6,
            };
            row.AddChild(text);

            var id = record.Id;
            if (requests)
            {
                row.AddChild(CreateButton("bank-ui-manage-approve", () => OnRequestReply?.Invoke(id, true)));
                row.AddChild(CreateButton("bank-ui-manage-reject", () => OnRequestReply?.Invoke(id, false)));
            }
            else
            {
                row.AddChild(CreateButton("bank-ui-manage-revoke", () => OnRevokeFine?.Invoke(id)));
            }

            list.AddChild(row);
        }
    }

    private static Button CreateButton(LocId text, Action action)
    {
        var button = new Button { Text = Loc.GetString(text), VerticalAlignment = VAlignment.Center };
        button.OnPressed += _ => action();
        return button;
    }

    private void SendAmount(Action<int, int, string>? action)
    {
        if (_state?.Selected is not { } number || !int.TryParse(AmountInput.Text, out var amount))
            return;

        action?.Invoke(number, amount, CommentInput.Text);
        AmountInput.Clear();
    }

    private void UpdateButtons()
    {
        var hasComment = CommentInput.Text.Trim().Length > 0;
        var hasAmount = int.TryParse(AmountInput.Text, out var amount);
        BonusButton.Disabled = !hasComment || !hasAmount || amount <= 0;
        FineButton.Disabled = !hasComment || !hasAmount || amount <= 0;
        SetBalanceButton.Disabled = !hasComment || !hasAmount;

        foreach (var row in HistoryList.Children)
        {
            foreach (var child in row.Children)
            {
                if (child is Button button)
                    button.Disabled = !hasComment;
            }
        }
    }
}
