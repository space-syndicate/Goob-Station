using Content.Client._Aquila.PDA;
using Content.Shared._Aquila.Economy;
using Content.Shared._Aquila.Economy.DataDefinitions;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Aquila.Economy;

[GenerateTypedNameReferences]
public sealed partial class BankUiFragment : BoxContainer
{
    public event Action<int, int>? OnTransfer;
    public event Action<int, int, string>? OnBonus;
    public event Action<int, int, string>? OnFine;
    public event Action<int, bool>? OnRequestReply;
    public event Action<int>? OnRevokeFine;
    public event Action? OnOpenAccount;

    public BankUiFragment()
    {
        RobustXamlLoader.Load(this);

        TransferButton.OnPressed += _ => Transfer();
        AmountInput.OnTextEntered += _ => Transfer();
        BonusButton.OnPressed += _ => Manage(OnBonus);
        FineButton.OnPressed += _ => Manage(OnFine);
        OpenAccountButton.OnPressed += _ => OnOpenAccount?.Invoke();
    }

    /// <summary>
    /// Обновляет данные счёта, баланс, раздел премий и штрафов и историю операций.
    /// </summary>
    public void UpdateState(BankUiState state)
    {
        NoAccountCard.Visible = state.Number == null;
        OpenAccountButton.Visible = state.CanOpen;
        NoAccountLabel.Text = Loc.GetString(state.Offline ? "bank-offline" : "bank-ui-no-account");
        AccountContainer.Visible = state.Number != null;
        if (state.Number == null)
            return;

        BalanceLabel.Text = Loc.GetString("bank-ui-balance", ("balance", state.Balance));
        BalanceLabel.FontColorOverride = state.Balance < 0 ? PdaStyle.Red : null;
        OwnerLabel.Text = state.JobTitle == null
            ? state.OwnerName
            : Loc.GetString("bank-ui-owner", ("name", state.OwnerName ?? string.Empty), ("job", state.JobTitle));
        OwnerLabel.ToolTip = OwnerLabel.Text;
        NumberLabel.Text = Loc.GetString("bank-ui-number", ("number", state.Number.Value.ToString()));

        ManageContainer.Visible = state.Manage != null;
        if (state.Manage is { } manage)
        {
            BudgetNameLabel.Text = manage.BudgetName;
            BudgetBalanceLabel.Text = Loc.GetString("bank-ui-credits", ("amount", manage.BudgetBalance));
            BonusLeftLabel.Text = Loc.GetString("bank-ui-credits", ("amount", manage.BonusLeft));
            MaxFineLabel.Text = manage.MaxFine is { } maxFine
                ? Loc.GetString("bank-ui-credits", ("amount", maxFine))
                : Loc.GetString("bank-ui-manage-unlimited");
            ManageCommentInput.IsValid = text => text.Length <= manage.MaxCommentLength;

            RequestsContainer.Visible = manage.Requests.Count > 0;
            RequestsList.RemoveAllChildren();
            foreach (var request in manage.Requests)
            {
                var row = CreateRecordRow(request);
                var buttons = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 6 };
                buttons.AddChild(CreateRecordButton("bank-ui-manage-approve", () => OnRequestReply?.Invoke(request.Id, true)));
                buttons.AddChild(CreateRecordButton("bank-ui-manage-reject", () => OnRequestReply?.Invoke(request.Id, false)));
                row.AddChild(buttons);
                RequestsList.AddChild(row);
            }

            FinesContainer.Visible = manage.Fines.Count > 0;
            FinesList.RemoveAllChildren();
            foreach (var fine in manage.Fines)
            {
                var row = CreateRecordRow(fine);
                row.AddChild(CreateRecordButton("bank-ui-manage-revoke", () => OnRevokeFine?.Invoke(fine.Id)));
                FinesList.AddChild(row);
            }
        }

        HistoryContainer.RemoveAllChildren();
        if (state.History.Count == 0)
        {
            HistoryContainer.AddChild(new Label
            {
                Text = Loc.GetString("bank-ui-history-empty"),
                StyleClasses = { "LabelSubText" },
                Margin = new Thickness(10, 6),
            });
            return;
        }

        for (var i = state.History.Count - 1; i >= 0; i--)
        {
            if (i != state.History.Count - 1)
                HistoryContainer.AddChild(new PanelContainer { StyleClasses = { "PdaSeparator" }, SetHeight = 1 });

            HistoryContainer.AddChild(CreateRow(state.History[i]));
        }
    }

    private void Transfer()
    {
        if (!int.TryParse(NumberInput.Text, out var number) || !int.TryParse(AmountInput.Text, out var amount))
            return;

        OnTransfer?.Invoke(number, amount);
        AmountInput.Clear();
    }

    private void Manage(Action<int, int, string>? action)
    {
        if (!int.TryParse(ManageNumberInput.Text, out var number) || !int.TryParse(ManageAmountInput.Text, out var amount))
            return;

        action?.Invoke(number, amount, ManageCommentInput.Text);
        ManageAmountInput.Clear();
        ManageCommentInput.Clear();
    }

    private static BoxContainer CreateRecordRow(BankManageRecordUiData record)
    {
        var title = Loc.GetString(record.Fine ? "bank-ui-manage-record-fine" : "bank-ui-manage-record-bonus",
            ("amount", record.Amount),
            ("target", record.TargetName));
        var details = Loc.GetString("bank-ui-manage-record-details",
            ("issuer", record.IssuerName),
            ("budget", record.BudgetName),
            ("comment", record.Comment));

        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };
        row.AddChild(new Label
        {
            Text = title,
            ToolTip = title,
            FontColorOverride = record.Fine ? PdaStyle.Red : PdaStyle.Accent,
            ClipText = true,
        });
        row.AddChild(new Label
        {
            Text = details,
            ToolTip = details,
            StyleClasses = { "LabelSubText" },
            ClipText = true,
        });
        return row;
    }

    private static Button CreateRecordButton(LocId text, Action action)
    {
        var button = new Button
        {
            Text = Loc.GetString(text),
            HorizontalExpand = true,
            StyleClasses = { "GreenPDAPalette" },
        };
        button.OnPressed += _ => action();
        return button;
    }

    private static BoxContainer CreateRow(BankTransaction transaction)
    {
        var reason = Loc.GetString(transaction.Reason, ("party", transaction.Party ?? string.Empty));

        var top = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
        top.AddChild(new Label
        {
            Text = reason,
            ToolTip = reason,
            HorizontalExpand = true,
            ClipText = true,
        });
        top.AddChild(new Label
        {
            Text = Loc.GetString(transaction.Amount > 0 ? "bank-ui-income" : "bank-ui-expense", ("amount", Math.Abs(transaction.Amount))),
            FontColorOverride = transaction.Amount > 0 ? PdaStyle.Accent : PdaStyle.Red,
        });

        var bottom = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };
        bottom.AddChild(new Label
        {
            Text = transaction.Time.ToString(@"hh\:mm\:ss"),
            StyleClasses = { "LabelSubText" },
        });
        if (transaction.Comment != null)
        {
            bottom.AddChild(new Label
            {
                Text = transaction.Comment,
                ToolTip = transaction.Comment,
                StyleClasses = { "LabelSubText" },
                HorizontalExpand = true,
                ClipText = true,
            });
        }

        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 6),
        };
        row.AddChild(top);
        row.AddChild(bottom);
        return row;
    }
}
