using Content.Shared._BlackM.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client._BlackM.DiscordAuth;

[GenerateTypedNameReferences]
public sealed partial class DiscordAuthWindow : DefaultWindow
{
    [Dependency] private Content.Corvax.Interfaces.Client.IClientDiscordAuthManager _discordAuthManager = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IUriOpener _uriOpener = default!;

    public DiscordAuthWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ByPassBtn.Visible = _discordAuthManager.IsOpt;
        ByPassBtn.OnPressed += _ => _discordAuthManager.ByPass();

        OpenServerButton.OnPressed += _ =>
        {
            var url = _cfg.GetCVar(BlackMCVars.DiscordAuthInviteUrl);
            if (url.StartsWith("https://"))
                _uriOpener.OpenUri(url);
        };

        RefreshData();
        _discordAuthManager.DataUpdated += RefreshData;
    }

    private void RefreshData()
    {
        var hasCode = _discordAuthManager.LinkCode != string.Empty;

        LinkInfoLabel.Text = hasCode
            ? Loc.GetString("discord-auth-join-code")
            : Loc.GetString("discord-auth-join-wait");

        CodeEdit.TextRope = new Rope.Leaf(hasCode ? _discordAuthManager.LinkCode : "...");
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
            _discordAuthManager.DataUpdated -= RefreshData;
    }
}
