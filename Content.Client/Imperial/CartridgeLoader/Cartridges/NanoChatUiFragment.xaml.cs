using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared.Imperial.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Imperial.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NanoChatUiFragment : BoxContainer
{
    public event Action? OnNotificationSwitchPressed;
    public event Action<string>? OnSendMessage;
    public event Action<NanoChatContact>? OnContactSelected;

    private string? _pdaCardName;

    public NanoChatUiFragment()
    {
        RobustXamlLoader.Load(this);

        ContactsButton.OnPressed += _ =>
        {
            ContactsPanel.Visible = !ContactsPanel.Visible;
        };

        NotificationSwitch.OnPressed += _ => OnNotificationSwitchPressed?.Invoke();

        SendButton.OnPressed += _ => SendMessage();
        MessageInput.OnTextEntered += _ => SendMessage();
    }

    private static string GetJobTitle(string? jobTitle)
    {
        return jobTitle is null or "nano-chat-ui-contact-job-unknown"
            ? Loc.GetString("nano-chat-ui-contact-job-unknown")
            : jobTitle;
    }

    private void SendMessage()
    {
        var text = MessageInput.Text;
        if (string.IsNullOrWhiteSpace(text))
            return;

        AddMessageBubble(_pdaCardName, text);
        ChatScroll.SetScrollValue(new Vector2(0f, float.MaxValue));

        OnSendMessage?.Invoke(text);
        MessageInput.Text = string.Empty;
    }

    public void UpdateState(NanoChatBoundUserInterfaceState state)
    {
        _pdaCardName = state.PdaCardName;

        NotificationSwitch.Text = Loc.GetString(
            state.NotificationOn
                ? "news-read-ui-notification-on"
                : "news-read-ui-notification-off");

        CurrentContactLabel.Text = state.CurrentContactName is { } cont
            ? Loc.GetString(
                "nano-chat-ui-contact-name-job-inline",
                ("name", cont.Name),
                ("job", GetJobTitle(cont.JobTitle)))
            : Loc.GetString("nano-chat-ui-no-contact-selected");

        ContactsListContainer.DisposeAllChildren();

        foreach (var contact in state.Contacts)
        {
            var text = Loc.GetString(
                "nano-chat-ui-contact-name-job",
                ("name", contact.Name),
                ("job", GetJobTitle(contact.JobTitle)));

            var btn = new Button
            {
                Text = text,
                Margin = new Thickness(0, 0, 0, 2),
            };

            btn.OnPressed += _ =>
            {
                ContactsPanel.Visible = false;

                if (state.CurrentContactName == contact)
                    return;

                CurrentContactLabel.Text = Loc.GetString(
                    "nano-chat-ui-contact-name-job-inline",
                    ("name", contact.Name),
                    ("job", GetJobTitle(contact.JobTitle)));

                MessageContainer.DisposeAllChildren();
                MessageContainer.AddChild(new RichTextLabel
                {
                    Margin = new Thickness(0, 0, 0, 5),
                    Text = "Загрузка...",
                });

                OnContactSelected?.Invoke(contact);
            };

            ContactsListContainer.AddChild(btn);
        }

        MessageContainer.DisposeAllChildren();

        foreach (var msg in state.Messages)
            AddMessageBubble(msg.Sender, msg.Content);
    }

    private void AddMessageBubble(string? senderName, string content)
    {
        var displaySender = senderName;

        if (string.IsNullOrEmpty(senderName))
            displaySender = Loc.GetString("nano-chat-ui-unknown-sender");
        else if (senderName == _pdaCardName)
            displaySender = Loc.GetString("nano-chat-ui-you-text");

        var wrapper = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };

        var panel = new PanelContainer
        {
            StyleClasses = { StyleClass.BackgroundPanelDark },
            HorizontalExpand = false,
        };

        if (senderName == _pdaCardName)
        {
            wrapper.AddChild(new Control { HorizontalExpand = true });
            wrapper.AddChild(panel);
        }
        else
        {
            wrapper.AddChild(panel);
            wrapper.AddChild(new Control { HorizontalExpand = true });
        }

        var label = new RichTextLabel();
        label.SetMessage(
            FormattedMessage.FromMarkupPermissive(
                $"[bold]{displaySender}:[/bold] {FormattedMessage.EscapeText(content)}"));

        panel.AddChild(label);
        MessageContainer.AddChild(wrapper);
    }
}
