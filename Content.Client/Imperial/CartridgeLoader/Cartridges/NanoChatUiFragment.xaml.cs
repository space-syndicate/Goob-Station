using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using Content.Shared.Imperial.CartridgeLoader.Cartridges;
using Robust.Client.UserInterface;

namespace Content.Client.Imperial.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class NanoChatUiFragment : BoxContainer
{
    public event Action? OnNotificationSwitchPressed;
    public event Action<string>? OnSendMessage;
    public event Action<string>? OnContactSelected;

    public NanoChatUiFragment()
    {
        RobustXamlLoader.Load(this);

        ContactsButton.OnPressed += _ =>
        {
            ContactsPanel.Visible = !ContactsPanel.Visible;
        };

        NotificationSwitch.OnPressed += _ => OnNotificationSwitchPressed?.Invoke();

        SendButton.OnPressed += _ => SendMessage();
        MessageInput.OnTextEntered += _ => SendMessage();
    }

    private void SendMessage()
    {
        if (string.IsNullOrWhiteSpace(MessageInput.Text))
            return;

        OnSendMessage?.Invoke(MessageInput.Text);
        MessageInput.Text = string.Empty;
    }

    public void UpdateState(NanoChatBoundUserInterfaceState state)
    {
        NotificationSwitch.Text = Loc.GetString(state.NotificationOn ? "news-read-ui-notification-on" : "news-read-ui-notification-off");

        CurrentContactLabel.Text = string.IsNullOrEmpty(state.CurrentContactName)
            ? Loc.GetString("nano-chat-ui-no-contact-selected")
            : state.CurrentContactName;

        ContactsListContainer.DisposeAllChildren();
        foreach (var contact in state.Contacts)
        {
            var btn = new Button
            {
                Text = contact,
                Margin = new Thickness(0, 0, 0, 2),
            };

            btn.OnPressed += _ =>
            {
                ContactsPanel.Visible = false;
                if (contact == state.CurrentContactName)
                    return;

                CurrentContactLabel.Text = contact;
                MessageContainer.DisposeAllChildren();
                MessageContainer.AddChild(new RichTextLabel
                {
                    Margin = new Thickness(0, 0, 0, 5),
                    Text = "Загрузка...",
                });
                OnContactSelected?.Invoke(contact);
            };

            ContactsListContainer.AddChild(btn);
        }

        MessageContainer.DisposeAllChildren();
        foreach (var msg in state.Messages)
        {
            var sender = msg.Sender;

            Log.Debug($"Sender: '{msg.Sender}'");
            Log.Debug($"PDA: '{state.PdaCardName}'");

            if (string.IsNullOrEmpty(msg.Sender))
                sender = Loc.GetString("nano-chat-ui-unknown-sender");
            else if (msg.Sender == state.PdaCardName)
                sender = Loc.GetString("nano-chat-ui-you-text");

            var wrapper = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            var panel = new PanelContainer
            {
                StyleClasses = { "BackgroundPanelDark" },
                HorizontalExpand = false,
            };

            if (msg.Sender == state.PdaCardName)
            {
                wrapper.AddChild(new Control { HorizontalExpand = true });
                wrapper.AddChild(panel);
            }
            else
            {
                wrapper.AddChild(panel);
                wrapper.AddChild(new Control { HorizontalExpand = true });
            }

            // var sender = (msg.Sender == state.PdaCardName)
            //     ? Loc.GetString("nano-chat-ui-you-text")
            //     : msg.Sender;

            //<PanelContainer StyleClasses="BackgroundPanelDark" HorizontalExpand="True" VerticalExpand="True" Margin="0 0 0 8">
            var label = new RichTextLabel();
            label.SetMessage(FormattedMessage.FromMarkupPermissive(
                $"[bold]{sender}:[/bold] {FormattedMessage.EscapeText(msg.Content)}"));

            panel.AddChild(label);
            MessageContainer.AddChild(wrapper);
        }
    }
}
